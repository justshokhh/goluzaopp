/**
 * Xavfsiz logotip URL manzillarini olish yordamchisi
 */
export const createLogoUrl = (name: string, _bg?: string, _text: string = 'ffffff'): string => {
  const lower = name.toLowerCase().trim();
  if (lower === 'sl' || lower.includes('superliga')) {
    return getTournamentLogo('uz_superliga');
  }
  if (lower === 'epl' || lower.includes('premier')) {
    return getTournamentLogo('premier_league');
  }
  if (lower === 'laliga' || lower.includes('la liga')) {
    return getTournamentLogo('laliga');
  }
  if (lower === 'ucl' || lower.includes('champions')) {
    return getTournamentLogo('ucl');
  }
  if (lower === 'uel' || lower.includes('europa')) {
    return getTournamentLogo('uel');
  }
  return getTeamLogo(name, name);
};

